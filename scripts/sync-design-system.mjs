#!/usr/bin/env node
/**
 * Copies the design system into this repository.
 *
 *   npm run sync:ds                       # uses ../inno-trec-design-system
 *   npm run sync:ds -- /path/to/design-system
 *   INNO_TREC_DS=/path/to/design-system npm run sync:ds
 *
 * What it does
 *   1. project/tokens.json                 -> packages/tokens/tokens.json (then rebuilds the tokens package)
 *   2. project/components/bundle.js         -> packages/ui-web/src/index.js   (ES module)
 *   3. project/components/index.d.ts       -> packages/ui-web/src/index.d.ts (types)
 *   4. project/components/bundle.css       -> packages/ui-web/src/styles.css (fonts + tokens + component styles)
 *   5. uploads/Logos/*.png                 -> packages/ui-web/assets/logos/
 *      uploads/Funding/*.png               -> packages/ui-web/assets/funding/ (EU funding emblem)
 *   6. reference documents                 -> docs/reference/ (brand book, DESIGN.md, open questions, component guide)
 *   7. writes design-system.lock.json with the version that was copied and a hash of every generated file
 *      (npm run check:generated compares them)
 *
 * The design system repository stays the source of truth. Never edit the generated files by hand.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { hashGenerated } from './generated-files.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ds = path.resolve(process.argv[2] ?? process.env.INNO_TREC_DS ?? path.join(root, '..', 'inno-trec-design-system'));
const read = (p) => fs.readFileSync(path.join(ds, p), 'utf8');
const rel = (p) => path.relative(root, p);

for (const required of ['project/tokens.json', 'project/components/bundle.js', 'project/components/index.d.ts', 'project/components/bundle.css']) {
  if (!fs.existsSync(path.join(ds, required))) {
    console.error(`Design system not found at ${ds}\nMissing: ${required}\nPass the path as the first argument or set INNO_TREC_DS.`);
    process.exit(1);
  }
}

const banner = '/* GENERATED by scripts/sync-design-system.mjs from the INNO-TREC design system. Do not edit by hand. */\n';

/* 1. tokens */
fs.copyFileSync(path.join(ds, 'project/tokens.json'), path.join(root, 'packages/tokens/tokens.json'));
execFileSync('node', [path.join(root, 'packages/tokens/scripts/build.mjs')], { stdio: 'inherit', cwd: root });

/* 2. components as an ES module */
let js = read('project/components/bundle.js');
const header = /\/\* @ds-bundle: (\{.*\}) \*\//.exec(js);
const names = header ? JSON.parse(header[1]).components.map((c) => c.name) : [];
if (!names.length) throw new Error('Could not read the component list from the @ds-bundle header.');
const must = (cond, msg) => { if (!cond) throw new Error(`bundle.js has a new shape (${msg}). Update scripts/sync-design-system.mjs.`); };
must(js.includes('var React = window.React;'), 'React global');
js = js.replace('var React = window.React;', '');
must(/\n\(function \(\) \{/.test(js), 'IIFE start');
js = js.replace('\n(function () {', '\nconst innoTrec = (function () {');
const tail = /\n  var ns = window\.InnoTrec \|\| \(window\.InnoTrec = \{\}\);\n  Object\.assign\(ns, (\{[\s\S]*?\})\);\n\}\)\(\);\s*$/;
must(tail.test(js), 'export block');
js = js.replace(tail, (_, obj) => `\n  return ${obj};\n})();\n\nexport const { ${names.join(', ')} } = innoTrec;\n`);
fs.writeFileSync(path.join(root, 'packages/ui-web/src/index.js'), `${banner}import React from 'react';\n${js}`);

/* 3. types (drop the window.InnoTrec global declaration) */
let dts = read('project/components/index.d.ts');
must(/declare global \{[\s\S]*\}\s*$/.test(dts), 'global declaration in index.d.ts');
dts = dts.replace(/declare global \{[\s\S]*\}\s*$/, '');
fs.writeFileSync(path.join(root, 'packages/ui-web/src/index.d.ts'), `${banner}${dts.trimEnd()}\n`);

/* 4. one stylesheet: fonts, token variables, component styles */
const css = read('project/components/bundle.css');
const fontImport = /^@import url\([^)]*\);\s*/m.exec(css);
must(fontImport, 'font @import');
const tokensCss = fs.readFileSync(path.join(root, 'packages/tokens/dist/tokens.css'), 'utf8').replace(/^\/\*.*\*\/\n/, '');
fs.writeFileSync(
  path.join(root, 'packages/ui-web/src/styles.css'),
  `${banner}${fontImport[0].trim()}\n\n${tokensCss}\n${css.replace(fontImport[0], '')}`,
);

/* 5. logos and the EU funding emblem */
const copyPngs = (from, to) => {
  const src = path.join(ds, from);
  const dest = path.join(root, to);
  fs.mkdirSync(dest, { recursive: true });
  const files = fs.existsSync(src) ? fs.readdirSync(src).filter((f) => f.endsWith('.png')) : [];
  for (const f of files) fs.copyFileSync(path.join(src, f), path.join(dest, f));
  return files;
};
const logos = copyPngs('uploads/Logos', 'packages/ui-web/assets/logos');
const funding = copyPngs('uploads/Funding', 'packages/ui-web/assets/funding');

/* 6. reference documents (owned by the design system; the hand-written docs link to them) */
const refDir = path.join(root, 'docs/reference');
fs.mkdirSync(refDir, { recursive: true });
const docBanner = '<!-- GENERATED by scripts/sync-design-system.mjs from the INNO-TREC design system. Do not edit by hand. -->\n\n';
const copyDoc = (from, to) => { if (fs.existsSync(path.join(ds, from))) fs.writeFileSync(path.join(refDir, to), docBanner + read(from)); };
copyDoc('project/README.md', 'brand-book.md');
copyDoc('DESIGN.md', 'DESIGN.md');
copyDoc('project/open-questions.md', 'open-questions.md');

const sections = names.map((name) => {
  const dir = `project/components/${name}`;
  if (!fs.existsSync(path.join(ds, dir, 'README.md'))) return '';
  const group = /@dsCard group="([^"]+)"/.exec(fs.existsSync(path.join(ds, dir, 'preview.html')) ? read(`${dir}/preview.html`) : '')?.[1];
  const body = read(`${dir}/README.md`).replace(/^# .*\n+/, '').trim();
  return `## ${name}\n\n${group ? `Group: ${group}\n\n` : ''}${body}\n`;
}).filter(Boolean);
fs.writeFileSync(
  path.join(refDir, 'components.md'),
  `${docBanner}# Component guide\n\nOne entry per component, copied from the design system. Props and types are in \`packages/ui-web/src/index.d.ts\`. For a live view of every component, open the design system gallery.\n\n${sections.join('\n')}`,
);

/* 7. lock file */
let source = {};
try { source = JSON.parse(read('artifact.json')); } catch { /* the design system folder has no artifact.json */ }
const lock = {
  designSystem: path.basename(ds),
  publishedVersion: source.lastPublishedVersion ?? null,
  publishedAt: source.lastPublishedAt ?? null,
  syncedAt: new Date().toISOString(),
  components: names.length,
  logos: logos.length,
  funding: funding.length,
  referenceDocs: ['brand-book.md', 'DESIGN.md', 'open-questions.md', 'components.md'],
  files: hashGenerated(root),
};
fs.writeFileSync(path.join(root, 'design-system.lock.json'), `${JSON.stringify(lock, null, 2)}\n`);

console.log(`synced ${names.length} components, ${logos.length} logos, ${funding.length} funding emblems from ${ds}`);
console.log(`wrote ${rel(path.join(root, 'design-system.lock.json'))}`);
