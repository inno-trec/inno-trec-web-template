#!/usr/bin/env node
/**
 * Builds everything in dist/ from tokens.json:
 *   tailwind-preset.cjs  Tailwind preset (web and NativeWind). Literal values only.
 *   tokens.css           CSS custom properties (:root) used by the component styles.
 *   tokens.cjs / .d.ts   Plain JS constants, for code that cannot use class names
 *                        (SVG fills, native status bar color, charts).
 *
 * tokens.json is a copy of the design system's project/tokens.json.
 * Update it with `npm run sync:ds` from the repository root, never by hand.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(pkg, 'dist');
const tokens = JSON.parse(fs.readFileSync(path.join(pkg, 'tokens.json'), 'utf8'));
fs.mkdirSync(dist, { recursive: true });

/* Resolve {alias} references such as on-green -> {ink}. */
const raw = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
const resolve = (v) => (v.startsWith('{') ? resolve(raw[v.slice(1, -1)]) : v);
const colors = Object.fromEntries(Object.keys(raw).map((k) => [k, resolve(raw[k])]));

const fontSize = {};
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    fontSize[s.name] = [s.fontSize, { lineHeight: s.lineHeight, fontWeight: String(s.fontWeight) }];
  }
}
const spacing = Object.fromEntries(tokens.spacing.tokens.map((t) => [t.name, t.value]));
const radius = { none: '0px', sm: '4px', full: '9999px' };
const fontFamily = {
  display: ['Figtree', 'system-ui', 'sans-serif'],
  sans: ['"Open Sans"', 'system-ui', 'sans-serif'],
  mono: ['ui-monospace', '"SF Mono"', 'Menlo', 'Consolas', 'monospace'],
};

/* ---- Tailwind preset ---- */
const preset = {
  // The component styles (ui-web) set their own base styles, so Tailwind's reset stays off.
  corePlugins: { preflight: false },
  theme: {
    extend: { colors, fontFamily, fontSize, spacing },
    borderRadius: radius, // square by default: no rounded-lg, rounded-xl and so on
    boxShadow: { none: 'none' }, // the system is flat: no shadow utilities
  },
};
fs.writeFileSync(
  path.join(dist, 'tailwind-preset.cjs'),
  `/* GENERATED by packages/tokens/scripts/build.mjs from tokens.json. Do not edit. */\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`,
);

/* ---- CSS custom properties ---- */
const decl = Object.entries(colors).map(([k, v]) => `  --${k}: ${v};`);
for (const fam of ['spacing', 'radius']) decl.push(...tokens[fam].tokens.map((t) => `  --${t.name}: ${t.value};`));
decl.push(...Object.entries(tokens.type.families).map(([k, v]) => `  --font-${k}: ${v};`));
fs.writeFileSync(
  path.join(dist, 'tokens.css'),
  `/* GENERATED by packages/tokens/scripts/build.mjs from tokens.json. Do not edit. */\n:root {\n${decl.join('\n')}\n}\n`,
);

/* ---- Plain constants ---- */
const constants = { colors, fontFamily: tokens.type.families, fontSize, spacing, radius };
fs.writeFileSync(
  path.join(dist, 'tokens.cjs'),
  `/* GENERATED by packages/tokens/scripts/build.mjs from tokens.json. Do not edit. */\nmodule.exports = ${JSON.stringify(constants, null, 2)};\n`,
);
const colorNames = Object.keys(colors).map((k) => JSON.stringify(k)).join(' | ');
fs.writeFileSync(
  path.join(dist, 'tokens.d.ts'),
  `/* GENERATED by packages/tokens/scripts/build.mjs from tokens.json. Do not edit. */
export type ColorName = ${colorNames};
export declare const colors: Record<ColorName, string>;
export declare const fontFamily: { display: string; text: string; mono: string };
export declare const fontSize: Record<string, [string, { lineHeight: string; fontWeight: string }]>;
export declare const spacing: Record<string, string>;
export declare const radius: Record<string, string>;
`,
);

console.log(`tokens: ${Object.keys(colors).length} colors, ${Object.keys(fontSize).length} text styles -> ${path.relative(process.cwd(), dist) || 'dist'}`);
